import { readFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { resolve, relative, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from 'espree';

const root = fileURLToPath(new URL('../', import.meta.url));
const runtimeModules = new Set([
  'sf/world/hud.js',
  'sf/world/interactions.js',
  'sf/world/runtime.js',
  'sf/world/network.js',
  'sf/world/rendering.js',
  'sf/world/minimap.js',
  'sf/config/dialogue.js',
  'sf/config/world-lore.js',
  'sf/rendering/character-gpu.js',
  'sf/rendering/dynamic-buffer.js',
  'sf/loading-screen.js',
  'sf/loading-npc.js',
  'sf/username-form.js',
  'sf/server-connection.js',
  'sf/debug-console.js',
  'sf/dialogue.js',
  'sf/dialogue-config.js',
  'sf/research-dialogue.js',
  'sf/rehabilitation.js',
]);
const isRuntime = (file) =>
  runtimeModules.has(file) ||
  file.startsWith('sf/dialogues/') ||
  file.startsWith('sf/ui/') ||
  file.startsWith('sf/client/') ||
  file.startsWith('sf/multiplayer-') ||
  file.endsWith('-ui.js') ||
  file.endsWith('-menu.js');
const canonical = (node) =>
  JSON.stringify(node, (key, value) =>
    ['start', 'end', 'range', 'loc', 'raw', 'comments', 'tokens'].includes(key) ? undefined : value,
  );

/** UI/network/texture artwork are built independently. Geometry and authored
 * placement modules remain conservative inputs; semantic ASTs ignore formatting. */
export async function worldInputs({
  readSource = (file) => readFile(resolve(root, file), 'utf8'),
} = {}) {
  const pending = ['sf/world/generation.js', 'sf/world/navigation.js'],
    seen = new Set(),
    inputs = new Map();
  const composition = parse(await readSource('sf/world/scene.js'), {
    ecmaVersion: 'latest',
    sourceType: 'module',
  });
  const scene = composition.body.find(
    (n) => n.type === 'ExportNamedDeclaration' && n.declaration?.id?.name === 'createSFWorld',
  ).declaration;
  const factories = new Set([
    'createGeneration',
    'createRuntime',
    'createRendering',
    'createInteractions',
    'createMinimap',
    'createNavigation',
    'createHud',
    'createNetwork',
  ]);
  const browserBindings = new Set([
    'context',
    '$',
    'world',
    'canvas',
    'map',
    'gl',
    'mc',
    'classic',
    'sections',
    'dialogue',
    'aiInterview',
    'connectionGate',
    'debugConsole',
    'frameMeter',
    'growthTicker',
    'clientController',
  ]);
  const initialization = [];
  for (const node of scene.body.body) {
    if (
      node.type === 'IfStatement' &&
      node.test.type === 'Identifier' &&
      node.test.name === 'headless'
    )
      break;
    if (node.type === 'VariableDeclaration') {
      const declarations = node.declarations
        .filter((d) => d.id.type !== 'Identifier' || !browserBindings.has(d.id.name))
        .filter((d) => !factories.has(d.init?.callee?.name));
      if (declarations.length) initialization.push({ ...node, declarations });
    } else if (['ExpressionStatement', 'ForStatement', 'ForOfStatement'].includes(node.type))
      initialization.push(node);
  }
  inputs.set('sf/world/scene.js#layout', canonical(initialization));
  for (const node of composition.body)
    if (node.type === 'ImportDeclaration' && !factories.has(node.specifiers[0]?.imported?.name)) {
      if (node.source.value.startsWith('.'))
        pending.push(relative(root, resolve(root, 'sf/world', node.source.value)));
    }
  while (pending.length) {
    const file = pending.pop();
    if (seen.has(file) || isRuntime(file)) continue;
    seen.add(file);
    const ast = parse(await readSource(file), { ecmaVersion: 'latest', sourceType: 'module' });
    inputs.set(file, canonical(ast));
    for (const node of ast.body)
      if (node.source?.value?.startsWith('.'))
        pending.push(relative(root, resolve(dirname(resolve(root, file)), node.source.value)));
  }
  // Changes to codecs or the compiler itself invalidate generated bytes.
  for (const file of [
    'sf/build-world.mjs',
    'sf/build-world-inputs.mjs',
    'sf/world-codec.js',
    'sf/world-tile-codec.js',
  ])
    if (!inputs.has(file))
      inputs.set(
        file,
        canonical(parse(await readSource(file), { ecmaVersion: 'latest', sourceType: 'module' })),
      );
  return inputs;
}
export async function worldInputVersion(options) {
  const inputs = await worldInputs(options),
    hash = createHash('sha256');
  for (const [file, source] of [...inputs].sort(([a], [b]) => a.localeCompare(b)))
    hash.update(file).update(source);
  return hash.digest('hex').slice(0, 20);
}
